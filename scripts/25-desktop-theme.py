#!/usr/bin/env python3
"""Generate the Bashan Plasma desktop theme and the fastfetch ASCII logo.

Plasma themes fall back per file: anything the theme does not provide comes
from Breeze. So this ships only what we actually want to change - the panel
background, which is the floating dock pill - and inherits the rest. That
keeps the theme to two files instead of several hundred.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

from _palette import ROOT, VARIANTS

THEMES = ROOT / "theme/rootfs/usr/share/plasma/desktoptheme"
ASCII_OUT = ROOT / "theme/rootfs/usr/share/bashan/logo-ascii.txt"

# 9-slice geometry for the pill. Plasma stretches `center` and the four
# edges, and leaves the four corners alone, so the corner boxes must be at
# least as big as the corner radius.
C = 34          # corner box size
E = 12          # width of the stretchable edge strips
R = 30          # visual corner radius


def panel_svg(v) -> str:
    """Floating dock pill, as a FrameSvg Plasma can 9-slice.

    Element ids are fixed by Plasma: center, top, bottom, left, right and the
    four corners. Each lives at its own offset inside one canvas.
    """
    # Read from the palette, so the light pill is a palette change rather
    # than a second copy of this function. A light pill needs a higher
    # opacity and a darker border than a dark one: a pale translucent pill
    # with a pale border on a pale wallpaper has no edge at all.
    fill = v.pal["dock_fill"]
    stroke = v.pal["dock_stroke"]
    op = v.pal["dock_opacity"]
    w = C * 2 + E
    parts = []

    def rect(eid, x, y, ww, hh, rx=0, extra=""):
        parts.append(
            f'  <rect id="{eid}" x="{x}" y="{y}" width="{ww}" height="{hh}" '
            f'rx="{rx}" ry="{rx}" fill="{fill}" fill-opacity="{op}" {extra}/>')

    def edge(eid, x, y, ww, hh, side):
        """An edge strip: fill plus a 1 px border line on its outer side."""
        parts.append(f'  <g id="{eid}">')
        parts.append(f'    <rect x="{x}" y="{y}" width="{ww}" height="{hh}" '
                     f'fill="{fill}" fill-opacity="{op}"/>')
        lx, ly, lw, lh = {
            "top":    (x, y, ww, 1),
            "bottom": (x, y + hh - 1, ww, 1),
            "left":   (x, y, 1, hh),
            "right":  (x + ww - 1, y, 1, hh),
        }[side]
        parts.append(f'    <rect x="{lx}" y="{ly}" width="{lw}" height="{lh}" '
                     f'fill="{stroke}" fill-opacity="0.85"/>')
        parts.append("  </g>")

    def corner(eid, x, y, cx, cy):
        """A rounded corner: a big rounded rect clipped to this corner box."""
        clip = f"clip{eid}"
        parts.append(f'  <clipPath id="{clip}">'
                     f'<rect x="{x}" y="{y}" width="{C}" height="{C}"/></clipPath>')
        parts.append(f'  <g id="{eid}" clip-path="url(#{clip})">')
        parts.append(f'    <rect x="{cx}" y="{cy}" width="{R * 2}" height="{R * 2}" '
                     f'rx="{R}" ry="{R}" fill="{fill}" fill-opacity="{op}" '
                     f'stroke="{stroke}" stroke-opacity="0.85" stroke-width="1"/>')
        parts.append("  </g>")

    # Layout inside the canvas: corners on the outside, edges between them.
    rect("center", C, C, E, E)
    edge("top", C, 0, E, C, "top")
    edge("bottom", C, C + E, E, C, "bottom")
    edge("left", 0, C, C, E, "left")
    edge("right", C + E, C, C, E, "right")
    corner("topleft", 0, 0, 0, 0)
    corner("topright", C + E, 0, C + E - (R * 2 - C), 0)
    corner("bottomleft", 0, C + E, 0, C + E - (R * 2 - C))
    corner("bottomright", C + E, C + E, C + E - (R * 2 - C), C + E - (R * 2 - C))

    return (f'<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'xmlns:xlink="http://www.w3.org/1999/xlink" '
            f'width="{w}" height="{w}" viewBox="0 0 {w} {w}">\n'
            f'  <!-- Bashan OS floating dock pill. Generated by '
            f'scripts/25-desktop-theme.py from theme/palette.json. -->\n'
            + "\n".join(parts) + "\n</svg>\n")


def ascii_logo(cols: int = 26) -> str:
    """Brightness-ramp ASCII rendering of the logo, for fastfetch."""
    im = Image.open(ROOT / "assets/branding/logo-source.jpg").convert("L")
    a = np.asarray(im)
    ys, xs = np.nonzero(a > 8)
    im = im.crop((xs.min(), ys.min(), xs.max(), ys.max()))
    rows = max(8, int(cols * im.height / im.width * 0.5))
    a = np.asarray(im.resize((cols, rows), Image.LANCZOS)).astype(np.float32)
    a = (a - a.min()) / max(float(np.ptp(a)), 1e-6)
    ramp = " .:-=+*#%@"
    idx = np.clip((a * (len(ramp) - 1)).round().astype(int), 0, len(ramp) - 1)
    return "\n".join("".join(ramp[i] for i in row) for row in idx) + "\n"


def main() -> None:
    for v in VARIANTS.values():
        theme = THEMES / v.desktoptheme
        (theme / "widgets").mkdir(parents=True, exist_ok=True)
        (theme / "metadata.json").write_text(json.dumps({
            "KPlugin": {
                "Id": v.desktoptheme,
                "Name": "Bashan" if not v.is_light else "Bashan Light",
                "Description": "Bashan OS desktop theme"
                               + ("" if not v.is_light else ", light"),
                "Authors": [{"Name": "Bashan Tech LLC"}],
                "License": "Proprietary",
                "Version": "1.0",
                "Website": "https://bashan.app",
            },
            "X-Plasma-API": "5.0",
        }, indent=4) + "\n")
        (theme / "widgets/panel-background.svg").write_text(panel_svg(v))
        (theme / "colors").write_text(
            (ROOT / f"theme/color-schemes/{v.scheme}.colors").read_text())
        print(f"   desktoptheme/{v.desktoptheme}/ "
              f"(metadata, colors, panel-background.svg)")

    ASCII_OUT.parent.mkdir(parents=True, exist_ok=True)
    art = ascii_logo()
    ASCII_OUT.write_text(art)
    print(f"   fastfetch ASCII logo: {len(art.splitlines())} lines")


if __name__ == "__main__":
    main()
