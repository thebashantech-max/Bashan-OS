#!/usr/bin/env python3
"""List every package in the image and the licence it declares.

The GPL requires source to be available to everyone who gets the binaries,
and that starts with knowing exactly what is in the image. This reads the
built chroot - not a guess, not the package lists we asked for, but what
dpkg says is actually installed - and writes:

    docs/legal/PACKAGE-LICENSES.csv   one row per package
    docs/legal/PACKAGE-LICENSES.md    the summary, and the non-free set

Licences come from each package's own machine-readable copyright file where
it has one, and from the free-text "License:" lines where it does not. A
package whose copyright file says nothing parseable is recorded as
UNPARSED rather than guessed at.

    ./scripts/60-package-licenses.py build/work/lb/chroot
"""
import csv
import re
import sys
from collections import Counter
from pathlib import Path

LICENSE_RE = re.compile(r"^License:\s*(.+?)\s*$", re.MULTILINE)


def read_status(root: Path):
    """Package name, version and section, straight from dpkg's status file."""
    status = root / "var/lib/dpkg/status"
    if not status.is_file():
        raise SystemExit(f"E: {status} not found - is that a built chroot?")
    out = []
    for block in status.read_text(errors="replace").split("\n\n"):
        if not block.strip():
            continue
        f = {}
        for line in block.splitlines():
            if line[:1] in (" ", "\t"):
                continue
            k, _, v = line.partition(":")
            f[k.strip()] = v.strip()
        if "install ok installed" not in f.get("Status", ""):
            continue
        if "Package" in f:
            out.append(f)
    return out


def licenses_for(root: Path, pkg: str) -> str:
    """Every distinct licence named in the package's copyright file."""
    p = root / "usr/share/doc" / pkg / "copyright"
    if not p.is_file():
        return "NO-COPYRIGHT-FILE"
    try:
        text = p.read_text(errors="replace")
    except OSError:
        return "UNREADABLE"
    names = []
    for m in LICENSE_RE.findall(text):
        # "GPL-2+ and BSD-3-clause" and similar: keep the whole phrase, it is
        # what the package actually claims.
        name = m.strip().rstrip(".")
        if name and name.lower() not in ("", "none") and name not in names:
            names.append(name)
    if not names:
        return "UNPARSED"
    return "; ".join(names[:6]) + (" ..." if len(names) > 6 else "")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    root = Path(sys.argv[1])
    repo = Path(__file__).resolve().parent.parent
    out_dir = repo / "docs/legal"
    out_dir.mkdir(parents=True, exist_ok=True)

    pkgs = read_status(root)
    rows = []
    for f in pkgs:
        name = f["Package"]
        rows.append({
            "package": name,
            "version": f.get("Version", ""),
            "source": (f.get("Source", name) or name).split()[0],
            "section": f.get("Section", ""),
            "licenses": licenses_for(root, name),
        })
    rows.sort(key=lambda r: r["package"])

    csv_path = out_dir / "PACKAGE-LICENSES.csv"
    with csv_path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["package", "version", "source",
                                           "section", "licenses"])
        w.writeheader()
        w.writerows(rows)

    # Debian puts non-free things in sections named non-free*/contrib.
    nonfree = [r for r in rows
               if r["section"].startswith(("non-free", "contrib"))]
    counts = Counter()
    for r in rows:
        first = r["licenses"].split(";")[0].strip()
        counts[first] += 1
    unparsed = [r for r in rows
                if r["licenses"] in ("UNPARSED", "NO-COPYRIGHT-FILE",
                                     "UNREADABLE")]

    md = out_dir / "PACKAGE-LICENSES.md"
    with md.open("w") as fh:
        fh.write(f"""# Packages in the image, and their licences

Generated by `scripts/60-package-licenses.py` from the built chroot, so this
is what dpkg reports as installed, not what the package lists asked for.

**{len(rows)} packages.** The full table, one row per package with its
version and source package, is in `PACKAGE-LICENSES.csv` beside this file —
it is too long to read here and is meant to be opened in a spreadsheet or
searched.

The source code for every one of these is obtainable as described in
`NOTICES.md` under *Written offer of source code*. The `source` column in
the CSV gives the Debian **source** package name, which is what to ask for:
several binary packages often come from one source package.

## Most common declared licences

| Licence as declared | Packages |
|---|---|
""")
        for name, n in counts.most_common(25):
            fh.write(f"| `{name}` | {n} |\n")
        fh.write(f"""
That column is the **first** licence each package declares. Many packages
declare several — the CSV has the full set for each.

## Non-free and contrib — {len(nonfree)} packages

These are not free software. Each is redistributable only under its own
vendor's terms, reproduced in the running system at
`/usr/share/doc/<package>/copyright`.

| Package | Version | Section |
|---|---|---|
""")
        for r in nonfree:
            fh.write(f"| `{r['package']}` | {r['version']} | {r['section']} |\n")
        fh.write(f"""
## Packages whose licence could not be read automatically — {len(unparsed)}

These need a person to open the copyright file and read it. An automated
tool saying nothing is not the same as a package having no licence.

""")
        for r in unparsed[:200]:
            fh.write(f"- `{r['package']}` ({r['licenses']})\n")
        if len(unparsed) > 200:
            fh.write(f"\n...and {len(unparsed) - 200} more; see the CSV.\n")

    print(f"I: {len(rows)} packages, {len(nonfree)} non-free/contrib, "
          f"{len(unparsed)} unparsed")
    print(f"I: {csv_path.relative_to(repo)}")
    print(f"I: {md.relative_to(repo)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
