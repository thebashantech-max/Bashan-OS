#!/usr/bin/env python3
"""Turn i18n/strings.json into every form the system needs.

One catalogue, four outputs:
  * Name[xx]= / Comment[xx]= lines merged into the .desktop files
  * a POSIX shell catalogue per language for the Chrome installer script
  * a JavaScript map embedded in the Calamares slideshow
  * i18n/REVIEW.csv for a native speaker to correct

Confidence is carried through from the catalogue and printed, because some
of these translations are not ones anybody should trust unreviewed.
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAT = json.loads((ROOT / "i18n/strings.json").read_text())
LANGS = list(CAT["languages"])
META = CAT["languages"]
S = CAT["strings"]

# Which catalogue key supplies which .desktop field.
DESKTOP = {
    "apps/rootfs/usr/share/applications/bashan-app.desktop": {
        "Comment": "app.bashan.comment"},
    "apps/rootfs/usr/share/applications/google-chrome.desktop": {
        "Comment": "app.chrome.comment"},
    "apps/rootfs/usr/share/applications/install-bashan-os.desktop": {
        "Name": "app.installer.name", "Comment": "app.installer.comment"},
}
SHELL_KEYS = ["chrome.title", "chrome.already", "chrome.ask", "chrome.busy",
              "chrome.ok", "chrome.cancelled", "chrome.failed",
              "nv.title", "nv.none", "nv.already", "nv.ask", "nv.sb",
              "nv.busy", "nv.ok", "nv.ok.mok", "nv.failed", "nv.cancelled"]
SLIDE_KEYS = [f"slide{n}.{p}" for n in (1, 2, 3, 4, 5) for p in ("title", "body")]


def check():
    missing = [(k, l) for k, v in S.items() for l in LANGS if not v["t"].get(l)]
    if missing:
        for k, l in missing:
            print(f"E: {k} has no {l} translation")
        raise SystemExit(1)
    print(f"I: {len(S)} strings x {len(LANGS)} languages, none missing")


def desktop_files():
    for rel, fields in DESKTOP.items():
        p = ROOT / rel
        lines = [ln for ln in p.read_text().splitlines()
                 if not re.match(r"^(Name|Comment|GenericName)\[", ln)]
        out = []
        for ln in lines:
            out.append(ln)
            for field, key in fields.items():
                if ln.startswith(field + "="):
                    for l in LANGS:
                        if l == "en":
                            continue
                        # .desktop wants one line; newlines become spaces.
                        txt = S[key]["t"][l].replace("\n", " ").strip()
                        out.append(f"{field}[{l}]={txt}")
        p.write_text("\n".join(out) + "\n")
        print(f"   {rel.split('/')[-1]}: +{(len(LANGS) - 1) * len(fields)} translated lines")


def shell_catalogues():
    d = ROOT / "apps/rootfs/usr/share/bashan/i18n"
    d.mkdir(parents=True, exist_ok=True)
    for l in LANGS:
        body = [f"# Bashan OS - {META[l]['name']} ({META[l]['native']})",
                f"# Translation confidence: {META[l]['confidence']}. "
                f"Reviewed by a native speaker: {'yes' if META[l]['reviewed'] else 'NO'}.",
                "# Generated from i18n/strings.json - do not edit by hand.", ""]
        for k in SHELL_KEYS:
            var = "BT_" + k.replace(".", "_").upper()
            txt = S[k]["t"][l].replace("\\", "\\\\").replace("'", "'\\''")
            body.append(f"{var}='{txt}'")
        (d / f"{l}.sh").write_text("\n".join(body) + "\n")
    print(f"   shell catalogues: {len(LANGS)} files in usr/share/bashan/i18n/")


def slideshow():
    p = ROOT / "installer/branding/bashan/show.qml"
    t = p.read_text()
    rows = []
    for l in LANGS:
        pairs = ",\n        ".join(
            f'"{k}": {json.dumps(S[k]["t"][l], ensure_ascii=False)}'
            for k in SLIDE_KEYS)
        rows.append(f'    "{l}": {{\n        {pairs}\n    }}')
    # Delimited so this is idempotent. The previous version matched on a
    # lookahead that never fired, so every run APPENDED another copy of the
    # whole catalogue: the file reached six `readonly property var tr`
    # declarations in one QML object, which is a syntax error, and the
    # slideshow would not have loaded.
    BEGIN = "    // ---- BEGIN generated by scripts/40-i18n.py ----\n"
    END = "    // ---- END generated ----\n"
    block = (BEGIN
             + "    // Translations from i18n/strings.json, embedded rather than\n"
               "    // compiled into .qm files: no Qt translation toolchain is\n"
               "    // needed at build time.\n"
               "    readonly property var tr: {\n"
             + ",\n".join(rows) + "\n    }\n\n"
               "    readonly property string lang: {\n"
               "        var n = Qt.locale().name.split(\"_\")[0];\n"
               "        return tr.hasOwnProperty(n) ? n : \"en\";\n"
               "    }\n"
               "    function t(key) { return tr[lang][key] || tr[\"en\"][key]; }\n"
             + END)
    t = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", t, flags=re.S)
    t = t.replace("    function nextSlide() {", block + "\n    function nextSlide() {", 1)
    for k in SLIDE_KEYS:
        en = S[k]["t"]["en"]
        t = t.replace(f'qsTr("{en}")', f'presentation.t("{k}")')
    p.write_text(t)
    print(f"   show.qml: {len(SLIDE_KEYS)} strings x {len(LANGS)} languages embedded")


def welcome_catalogue():
    """Emit the welcome app's strings as JSON it reads at runtime.

    The Calamares slideshow embeds its four strings directly into show.qml,
    which is fine for four. The welcome app has 41 in 13 languages, so it
    reads a catalogue instead - and the catalogue carries the per-language
    confidence and the rtl flag, so the app can both mirror itself and say
    out loud when the translation it is showing has not been reviewed.
    """
    keys = sorted(k for k in S if k.startswith("w."))
    out = {
        "languages": {l: {"native": META[l]["native"], "rtl": META[l]["rtl"],
                          "confidence": META[l]["confidence"],
                          "reviewed": META[l]["reviewed"]} for l in LANGS},
        "strings": {l: {k: S[k]["t"][l] for k in keys} for l in LANGS},
    }
    d = ROOT / "apps/rootfs/usr/share/bashan/welcome"
    d.mkdir(parents=True, exist_ok=True)
    (d / "i18n.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1) + "\n")
    print(f"   welcome/i18n.json: {len(keys)} strings x {len(LANGS)} languages")


def review_csv():
    out = ROOT / "i18n/REVIEW.csv"
    with out.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["language", "language_name", "confidence", "reviewed",
                    "key", "where_it_appears", "english_source",
                    "our_translation", "CORRECTED_TRANSLATION", "reviewer_notes"])
        for l in LANGS:
            if l == "en":
                continue
            m = META[l]
            for k, v in S.items():
                w.writerow([l, f"{m['name']} ({m['native']})", m["confidence"],
                            "yes" if m["reviewed"] else "NO",
                            k, v["note"], v["t"]["en"], v["t"][l], "", ""])
    rows = (len(LANGS) - 1) * len(S)
    print(f"   i18n/REVIEW.csv: {rows} rows for native-speaker review")


def welcome_image():
    """Bake the "installer not available in your language" note into the
    Calamares welcome image.

    Calamares has no field for arbitrary text on its first screen, and the
    people who need this note cannot read the installer's own language by
    definition. Putting it in the image shows it to everyone regardless of
    which UI language is active.

    Rendered through ImageMagick's Pango coder, not PIL: Pango shapes and
    bidi-orders Arabic and Syriac correctly, PIL does not.
    """
    import subprocess
    from PIL import Image

    out = ROOT / "installer/branding/bashan/welcome.png"
    note = S["installer.langnote"]["t"]
    lines = [
        ("en",  "DejaVu Sans 13",      note["en"],  False),
        ("ku",  "DejaVu Sans 13",      note["ku"],  False),
        ("ckb", "Noto Sans Arabic 14", note["ckb"], True),
        ("syr", "Noto Sans Syriac 14", note["syr"], True),
    ]
    W, PAD, COLW = 880, 20, 660
    rendered = []
    for code, font, text, rtl in lines:
        esc = (text.replace("&", "&amp;").replace("<", "&lt;")
                   .replace(">", "&gt;").replace("\n", " "))
        png = ROOT / f"build/work/_note-{code}.png"
        png.parent.mkdir(parents=True, exist_ok=True)
        cmd = ["convert", "-background", "none", "-size", f"{COLW}x",
               f'pango:<span font="{font}" foreground="#aebdd4">{esc}</span>',
               str(png)]
        try:
            subprocess.run(cmd, check=True, capture_output=True)
            rendered.append((Image.open(png).convert("RGBA"), rtl))
        except Exception as e:
            print(f"W: could not render the {code} note ({e}); skipping it")

    if not rendered:
        print("W: welcome image left without the language note")
        return

    H = PAD * 2 + sum(im.height + 14 for im, _ in rendered) + 140
    canvas = Image.new("RGBA", (W, H), (7, 11, 18, 255))
    logo = Image.open(ROOT / "installer/branding/bashan/logo.png")
    logo = logo.resize((120, 120), Image.LANCZOS)
    canvas.alpha_composite(logo, ((W - 120) // 2, PAD))

    y = PAD + 134
    for im, rtl in rendered:
        x = W - COLW - PAD if rtl else PAD + ((W - 2 * PAD) - COLW) // 2
        if not rtl:
            x = (W - COLW) // 2
        canvas.alpha_composite(im, (x, y))
        y += im.height + 14

    canvas.convert("RGB").save(out, optimize=True)
    for code, *_ in lines:
        (ROOT / f"build/work/_note-{code}.png").unlink(missing_ok=True)
    print(f"   welcome.png: language note in {len(rendered)} scripts "
          f"({W}x{H})")


def main():
    check()
    desktop_files()
    shell_catalogues()
    slideshow()
    welcome_catalogue()
    review_csv()
    welcome_image()
    unreviewed = [l for l in LANGS if not META[l]["reviewed"]]
    (ROOT / "i18n/UNREVIEWED").write_text(" ".join(unreviewed) + "\n")
    print("\n   translation confidence, as recorded in the catalogue:")
    for l in LANGS:
        m = META[l]
        flag = "" if m["reviewed"] else "   <- NOT reviewed by a native speaker"
        print(f"     {l:<4} {m['name']:<18} {m['confidence']:<9}{flag}")


if __name__ == "__main__":
    main()
